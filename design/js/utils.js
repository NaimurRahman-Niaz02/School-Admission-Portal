    /**
     * Escape HTML strings to prevent XSS
     */
    escapeHtml(str) {
      if (str === null || str === undefined) return '';
      return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
    },

    /**
     * Validate 17-digit numeric string
     */
    isValid17DigitId(id) {
      if (!id) return false;
      return /^\d{17}$/.test(String(id).trim());
    },

    /**
     * Alias for isValid17DigitId
     */
    isValidStudentId(id) {
      return this.isValid17DigitId(id);
    },

    /**
     * Format 17-digit birth registration number:
     * Shows first 4 and last 4 digits, masks the middle 9 digits.
     * e.g., "2008 •••• •••• 5678"
     */
    maskStudentId(id) {
      if (!id) return '';
      const clean = String(id).trim();
      if (clean.length !== 17) {
        return clean.length > 4 ? `•••• ${clean.slice(-4)}` : '••••';
      }
      const first4 = clean.slice(0, 4);
      const last4 = clean.slice(-4);
      return `${first4} •••• •••• ${last4}`;
    },

    /**
     * Human-friendly date and time formatting
     */
    formatDate(dateInput) {
      if (!dateInput) return '—';
      const date = new Date(dateInput);
      if (isNaN(date.getTime())) return '—';

      return new Intl.DateTimeFormat('en-US', {
        year: 'numeric',
        month: 'short',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
        hour12: true
      }).format(date);
    },

    /**
     * Format a compact date (e.g. Nov 09, 2026)
     */
